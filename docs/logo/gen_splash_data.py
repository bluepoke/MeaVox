# Run from docs/logo/: python3 gen_splash_data.py  (needs fonttools, uharfbuzz, skia-pathops)
"""Exports the MeaVox wordmark contours for the splash animation.

Same layout as meavox-logo.svg (Montserrat ExtraBold 800, 100 units per em, tracking 4, +2 between
"Mea" and "Vox"). Writes one SVG path string per contour so the animation can sample each contour
on its own (Compose PathMeasure / SVGPathElement.getPointAtLength).
"""
import json, re, sys
import uharfbuzz as hb
from fontTools.ttLib import TTFont
from fontTools.varLib import instancer
from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen
from fontTools.pens.boundsPen import BoundsPen

FONT = "/usr/share/fonts/truetype/google-fonts/ofl/montserrat/Montserrat[wght].ttf"
font = TTFont(FONT)
instancer.instantiateVariableFont(font, {"wght": 800}, overlap=instancer.OverlapMode.REMOVE).save("/tmp/mx.ttf")
font = TTFont("/tmp/mx.ttf")
gs = font.getGlyphSet()
upem = font["head"].unitsPerEm
hbfont = hb.Font(hb.Face(hb.Blob.from_file_path("/tmp/mx.ttf")))
buf = hb.Buffer(); buf.add_str("MeaVox"); buf.guess_segment_properties()
hb.shape(hbfont, buf, {"kern": True, "liga": False})

SCALE, TRACK = 100 / upem, 4.0
fmt = lambda v: f"{v:.2f}".rstrip("0").rstrip(".")
contours, x = [], 0.0
bounds = BoundsPen(gs)
for i, (info, p) in enumerate(zip(buf.glyph_infos, buf.glyph_positions)):
    name = font.getGlyphName(info.codepoint)
    pen = SVGPathPen(gs, ntos=fmt)
    gs[name].draw(TransformPen(pen, (SCALE, 0, 0, -SCALE, x, 0)))
    gs[name].draw(TransformPen(bounds, (SCALE, 0, 0, -SCALE, x, 0)))
    for d in re.findall(r"M[^M]*", pen.getCommands()):
        contours.append({"part": "mea" if i < 3 else "vox", "d": d.strip()})
    x += p.x_advance * SCALE + TRACK
    if i == 2:
        x += 2.0

xmin, ymin, xmax, ymax = bounds.bounds
data = {"bounds": [round(xmin, 2), round(ymin, 2), round(xmax, 2), round(ymax, 2)],
        "stroke": 3.4, "contours": contours}
json.dump(data, open("logo-contours.json", "w"), indent=1)

# Kotlin source with the same data
kt = ['// SPDX-License-Identifier: GPL-3.0-or-later',
      'package eu.schicht8.meavox.ui.splash',
      '',
      '/**',
      ' * The MeaVox wordmark (docs/logo/meavox-logo.svg) as one SVG path per contour, in logo units:',
      ' * 100 units per em, baseline at y = 0, y pointing down. Montserrat ExtraBold (SIL OFL 1.1), overlaps',
      ' * removed. Generated by docs/logo/gen_splash_data.py; regenerate rather than edit by hand.',
      ' */',
      'internal object LogoOutline {',
      f'    const val LEFT = {xmin:.2f}f',
      f'    const val TOP = {ymin:.2f}f',
      f'    const val RIGHT = {xmax:.2f}f',
      f'    const val BOTTOM = {ymax:.2f}f',
      '    const val STROKE = 3.4f',
      '',
      '    /** Contours of "Mea" (black fill, gold outline), left to right. */',
      '    val mea = listOf(']
kt += [f'        "{c["d"]}",' for c in contours if c["part"] == "mea"]
kt += ['    )', '', '    /** Contours of "Vox" (solid gold), left to right. */', '    val vox = listOf(']
kt += [f'        "{c["d"]}",' for c in contours if c["part"] == "vox"]
kt += ['    )', '}', '']
open("../../app/src/main/kotlin/eu/schicht8/meavox/ui/splash/LogoOutline.kt", "w").write("\n".join(kt))
print(len(contours), "contours", data["bounds"])
